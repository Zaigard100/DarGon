    private HelpDialog(String title, String[][] sections) {
        super(title);
        addCloseButton();
        closeOnEscape();
        setModal(true);
        setResizable(true);
        VisTable body = new VisTable();
        body.top().left();
        body.pad(8);
        for (String[] section : sections) {
            VisLabel heading = new VisLabel(section[0]);
            heading.setColor(1, 0.85f, 0.4f, 1);
            body.add(heading).left().padTop(10).row();
            VisLabel text = new VisLabel(section[1]);
            text.setWrap(true);
            text.setAlignment(Align.topLeft);
            body.add(text).width(640).left().padTop(2).row();
        }
        VisScrollPane pane = Form.wheel(new VisScrollPane(body));
        pane.setFadeScrollBars(false);
        pane.setScrollingDisabled(true, false);
        add(pane).width(680).height(520).row();
        VisTextButton ok = new VisTextButton("Понятно");
        ok.addListener(EditorApp.changed(this::fadeOut));
        add(ok).right().pad(6);
        pack();
        centerWindow();
    }

    static void show(Stage stage) {
        stage.addActor(new HelpDialog("Справка", SECTIONS).fadeIn());
    }

