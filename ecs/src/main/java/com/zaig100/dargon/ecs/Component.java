package com.zaig100.dargon.ecs;

/**
 * Компонент — набор данных сущности без игровой логики.
 *
 * <p>Экземпляры создаются фабрикой, зарегистрированной в {@link WorldBuilder#component}, и
 * переиспользуются через пул: при удалении компонента вызывается {@link #reset()}, после чего
 * объект может быть выдан другой сущности. Поэтому {@code reset()} обязан вернуть все поля к
 * значениям по умолчанию.
 */
public interface Component {

    /** Возвращает компонент в исходное состояние перед повторным использованием. */
    void reset();
}
